function csWeapon(id, name, recoil) {
  const d = FPS_DATA.cs2.weapons[id];
  const values = {
    game: 'cs2',
    interval: d.m_flCycleTime,
    magazine: d.m_iMaxClip1,
    // Attack-lock time is not advertised as a measured full reload animation.
    reload: d.m_flDisallowAttackAfterReloadStartDuration,
    damage: d.m_nDamage,
    headMultiplier: d.m_flHeadshotMultiplier,
    armorRatio: d.m_flArmorRatio,
    rangeModifier: d.m_flRangeModifier,
    maxSpeed: d.m_flMaxSpeed[0] * GAME_PROFILES.cs2.values.unitScale,
    spread: d.m_flSpread[0],
    standSpread: d.m_flInaccuracyStand[0],
    crouchSpread: d.m_flInaccuracyCrouch[0],
    moveSpread: d.m_flInaccuracyMove[0],
    recovery: d.m_flRecoveryTimeStand,
    recoilVertical: recoil[0],
    recoilHorizontal: recoil[1],
    recoilStart: recoil[2],
    recoilCap: recoil[3],
    adsZoom: 1,
    adsInterval: d.m_flCycleTime,
    adsSpread: d.m_flInaccuracyStand[0],
  };
  return profile(
    id,
    name,
    values,
    { ...weaponUnits, game: 'id', rangeModifier: 'ratio per 500 Source units' },
    {
      interval: 'm_flCycleTime',
      magazine: 'm_iMaxClip1',
      damage: 'm_nDamage',
      headMultiplier: 'm_flHeadshotMultiplier',
      armorRatio: 'm_flArmorRatio',
      rangeModifier: 'm_flRangeModifier',
      maxSpeed: 'm_flMaxSpeed[0] × unitScale',
      spread: 'm_flSpread[0]',
      standSpread: 'm_flInaccuracyStand[0]',
      crouchSpread: 'm_flInaccuracyCrouch[0]',
      moveSpread: 'm_flInaccuracyMove[0]',
      recovery: 'm_flRecoveryTimeStand',
    },
    FPS_SOURCES.cs2.weapons,
  );
}
