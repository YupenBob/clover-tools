/** Every gameplay field has a unit, source/version and explicit fidelity status. */
function profile(id, name, values, units, verified = {}, source = '') {
  return {
    id,
    name,
    values,
    evidence: Object.fromEntries(
      Object.keys(values).map((key) => [
        key,
        {
          unit: units[key] || 'ratio',
          status: key in verified ? 'source' : 'approximate',
          source:
            key in verified ? source : 'CloverTools training model; no original-game measurement',
          field: verified[key] || '',
          version:
            id === 'cs2' || id === 'ak47' || id === 'm4a1s'
              ? FPS_DATA.cs2.version
              : FPS_DATA.valorant.version,
        },
      ]),
    ),
  };
}
