import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { FPS_SOURCES } from '../config/fps-sources.mjs';

const sha = (value) => createHash('sha256').update(value).digest('hex');
async function read(url, filename) {
  if (process.env.FPS_DATA_INPUT_DIR)
    return readFile(join(process.env.FPS_DATA_INPUT_DIR, filename), 'utf8');
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return response.text();
}
function block(text, id) {
  const match = new RegExp(`\\b${id}\\s*=\\s*\\{`).exec(text);
  if (!match) throw new Error(`Missing weapon: ${id}`);
  const start = match.index + match[0].length;
  let depth = 1,
    end = start;
  while (depth && end < text.length) {
    if (text[end] === '{') depth++;
    if (text[end] === '}') depth--;
    end++;
  }
  if (depth) throw new Error(`Unclosed weapon: ${id}`);
  return text.slice(start, end - 1);
}
const [weapons, convars, valText, valVersionText] = await Promise.all([
  read(FPS_SOURCES.cs2.weapons, 'cs2-weapons.txt'),
  read(FPS_SOURCES.cs2.convars, 'cs2-convars.txt'),
  read(FPS_SOURCES.valorant.weapons, 'val-weapons.json'),
  read(FPS_SOURCES.valorant.versionUrl, 'val-version.json'),
]);
const valVersion = JSON.parse(valVersionText).data;
if (valVersion.version !== FPS_SOURCES.valorant.version)
  throw new Error(
    `VALORANT version changed to ${valVersion.version}; review sources before importing.`,
  );
const cs = {};
for (const [id, sourceId] of Object.entries(FPS_SOURCES.cs2.selected)) {
  const body = block(weapons, sourceId);
  cs[id] = Object.fromEntries(
    FPS_SOURCES.cs2.fields.map((field) => {
      const match = new RegExp(`\\b${field}\\s*=\\s*(\\[[^\\]]+\\]|[-\\d.]+)`).exec(body);
      if (!match) throw new Error(`Missing ${sourceId}.${field}`);
      const value = JSON.parse(match[1]);
      if ((Array.isArray(value) ? value : [value]).some((number) => !Number.isFinite(number)))
        throw new Error(`Invalid ${field}`);
      return [field, value];
    }),
  );
}
const variables = Object.fromEntries(
  FPS_SOURCES.cs2.variables.map((id) => {
    const match = new RegExp(`^${id} ([-\\d.]+)`, 'm').exec(convars);
    if (!match) throw new Error(`Missing convar ${id}`);
    return [id, Number(match[1])];
  }),
);
const val = JSON.parse(valText).data.filter((weapon) =>
  FPS_SOURCES.valorant.selected.includes(weapon.displayName),
);
if (val.length !== FPS_SOURCES.valorant.selected.length)
  throw new Error('Missing VALORANT weapons');
// Confirm that both endpoint responses belonged to the same release.
if (
  JSON.parse(await read(FPS_SOURCES.valorant.versionUrl, 'val-version.json')).data.version !==
  valVersion.version
)
  throw new Error('Release changed during import');
const data = {
  cs2: {
    version: FPS_SOURCES.cs2.version,
    revision: FPS_SOURCES.cs2.revision,
    sha256: { weapons: sha(weapons), convars: sha(convars) },
    variables,
    weapons: cs,
  },
  valorant: {
    version: valVersion.version,
    buildDate: valVersion.buildDate,
    sha256: sha(valText),
    weapons: Object.fromEntries(
      val.map((weapon) => [weapon.displayName.toLowerCase(), weapon.weaponStats]),
    ),
  },
};
await writeFile(
  new URL('../config/fps-data.mjs', import.meta.url),
  `// Generated by scripts/import-fps-data.mjs. Review version changes before refreshing.\nexport const FPS_DATA = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`FPS data imported: CS2 ${data.cs2.version}; VALORANT ${data.valorant.version}`);
