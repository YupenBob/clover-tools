const sharedErrors = [
  'cancelled', 'empty', 'manyFiles', 'animated', 'damaged', 'complex', 'inputLimit', 'headerLimit',
  'decodedLimit', 'decoderUnavailable', 'capacity', 'errorCanvas', 'outputLimit', 'outputDimensions',
  'invalidOptions', 'invalidWidth', 'invalidHeight', 'invalidQuality',
] as const;

export type ImageCompressCopy = Copy & Record<typeof sharedErrors[number], string>;

export function imageCompressCopy(lang: Lang): ImageCompressCopy {
  const convert = imageConvertCopy(lang);
  const errors = Object.fromEntries(sharedErrors.map(key => [key, convert[key]])) as Record<typeof sharedErrors[number], string>;
  const local = lang === 'tw'
    ? Object.fromEntries(Object.entries(zh).map(([key, value]) => [
      key,
      chineseS2t.s2t(value)
        .replaceAll('文件', '檔案')
        .replaceAll('體積', '檔案大小')
        .replaceAll('質量', '品質'),
    ])) as Copy
    : { zh, en, ja, ko }[lang];
  return { ...errors, ...local };
}
