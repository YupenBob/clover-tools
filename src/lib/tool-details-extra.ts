// Reviewed against the actual controls and algorithms. These are task-specific
// examples and limitations, not search-keyword filler or promises of future UI.
function detail(
  intro: string,
  steps: string[],
  examples: [string, string][],
  principle: string,
  pitfall: string,
  faqs: [string, string][],
  privacy = "工具输入在当前浏览器中处理。页面加载仍会向托管服务发送请求；站点级技术日志和第三方服务见隐私政策。",
): ToolDetail {
  return {
    intro,
    steps,
    examples: examples.map(([input, output], i) => ({
      label: i ? "另一种情况" : "操作示例",
      input,
      output,
    })),
    principles: [principle],
    pitfalls: [pitfall],
    faqs: faqs.map(([q, a]) => ({ q, a })),
    privacy,
  };
}

