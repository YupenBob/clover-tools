export function imageConvertCopy(lang: Lang): ImageConvertCopy {
  if (lang !== 'tw') return { zh, en, ko, ja }[lang];
  return Object.fromEntries(Object.entries(zh).map(([key, text]) => [
    key,
    chineseS2t.s2t(text)
      .replaceAll('文件', '檔案')
      .replaceAll(/標[籤簽]頁/g, '分頁')
      .replaceAll('瀏覽器會話', '瀏覽器工作階段')
      .replaceAll('質量', '品質'),
  ])) as ImageConvertCopy;
}
