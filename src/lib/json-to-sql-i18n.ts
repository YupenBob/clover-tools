export function jsonToSqlCopy(lang: Language): Copy {
  if (lang !== "tw") return { zh, en, ko, ja }[lang];
  const convert = (value: unknown): unknown =>
    typeof value === "string"
      ? chineseS2t
          .s2t(value)
          .replaceAll("字段", "欄位")
          .replaceAll("對象", "物件")
          .replaceAll("數據", "資料")
          .replaceAll("字符串", "字串")
          .replaceAll("生成", "產生")
          .replaceAll("匹配主鍵", "比對主鍵")
          .replaceAll("缺失欄位", "缺少欄位")
          .replaceAll("顯式空值", "明確空值")
          .replaceAll("標量值", "純量值")
      : Object.fromEntries(
          Object.entries(value as Record<string, unknown>).map(
            ([key, text]) => [key, convert(text)],
          ),
        );
  return convert(zh) as Copy;
}
