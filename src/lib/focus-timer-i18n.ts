const tw: FocusText = Object.fromEntries(
  Object.entries(zh).map(([k, v]) => [
    k,
    chineseS2t
      .s2t(v)
      .replaceAll("屏幕", "螢幕")
      .replaceAll("設置", "設定")
      .replaceAll("本周", "本週")
      .replaceAll("每周", "每週")
      .replaceAll("周一", "週一")
      // 簡繁轉換把「复制/复盘/内存」寫成「復制/復盤/內存」，
      // 台灣用語應為「複製/複盤/記憶體」。
      .replaceAll("復制", "複製")
      .replaceAll("復盤", "複盤")
      .replaceAll("內存", "記憶體"),
  ]),
) as FocusText;
export const focusText = (lang: FocusLang): FocusText =>
  ({ zh, tw, en, ja, ko })[lang];
export const sentence = (
  text: string,
  values: Record<string, string | number>,
) => text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ""));
export const focusLocale = (lang: FocusLang) =>
  ({ zh: "zh-CN", tw: "zh-TW", en: "en-US", ja: "ja-JP", ko: "ko-KR" })[lang];
